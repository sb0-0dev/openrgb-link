import { useEffect, useState } from "react";

import {
    checkServerHealth,
    exchangePairingCode,
  getServerVersion,
  ServerVersion,
} from "@/features/connection/api";
import {
  assertClientCompatible,
  ClientCompatibilityError,
} from "@/features/connection/version";
import {
    loadServerProfiles,
    saveServerProfiles,
    ServerProfile,
} from "@/features/connection/storage";
import {
    deleteAccessToken,
    getAccessToken,
    saveAccessToken,
} from "@/features/connection/token-store";
import { OpenRgbClient } from "@/services/openrgb/client";

/**
 * Reachability state for a saved server profile.
 * @remarks `checking` is used during initial load and explicit connection checks.
 */
export type ServerStatus = "checking" | "online" | "offline";

/**
 * Validates and canonicalizes a user-entered HTTP(S) server address.
 * @param value Raw URL entered in the pairing form.
 * @returns A normalized URL without a trailing slash.
 * @throws {Error} When the URL is invalid or does not use HTTP(S).
 */
function normalizeServerUrl(value: string): string {
  const trimmed = value.trim().replace(/\/+$/, "");
  let url: URL;
  try {
    url = new URL(trimmed);
  } catch {
    throw new Error(
      "Enter a complete server address, including http:// or https://.",
    );
  }
  if (url.protocol !== "http:" && url.protocol !== "https:") {
    throw new Error("The server address must start with http:// or https://.");
  }
  return url.toString().replace(/\/$/, "");
}

/** @returns A locally generated identifier for a newly paired profile. */
function newProfileId(): string {
  return `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
}

/**
 * Owns saved server profiles, reachability status, pairing, and the active session.
 * Profile metadata is persisted separately from the bearer token.
 * @returns Saved profiles, per-profile status, active connection data, and actions.
 */
export function useServerProfiles() {
  const [profiles, setProfiles] = useState<ServerProfile[]>([]);
  const [statuses, setStatuses] = useState<Record<string, ServerStatus>>({});
  const [isLoading, setIsLoading] = useState(true);
  const [profilesLoadFailed, setProfilesLoadFailed] = useState(false);
  const [activeProfileId, setActiveProfileId] = useState<string | null>(null);
  const [activeAccessToken, setActiveAccessToken] = useState<string | null>(
    null,
  );
  const [activeServerVersion, setActiveServerVersion] =
    useState<ServerVersion | null>(null);

  useEffect(() => {
    let isCurrent = true;

    loadServerProfiles()
      .then((savedProfiles) => {
        if (!isCurrent) return;
        setProfiles(savedProfiles);
        setStatuses(
          Object.fromEntries(savedProfiles.map(({ id }) => [id, "checking"])),
        );
        setIsLoading(false);

        for (const profile of savedProfiles) {
          checkServerHealth(new OpenRgbClient({ baseUrl: profile.baseUrl }))
            .then(() => {
              if (isCurrent) {
                setStatuses((current) => ({
                  ...current,
                  [profile.id]: "online",
                }));
              }
            })
            .catch(() => {
              if (isCurrent) {
                setStatuses((current) => ({
                  ...current,
                  [profile.id]: "offline",
                }));
              }
            });
        }
      })
      .catch(() => {
        if (isCurrent) {
          setProfilesLoadFailed(true);
          setIsLoading(false);
        }
      });

    return () => {
      isCurrent = false;
    };
  }, []);

  /**
   * Pairs a device and persists its profile and token.
   * @param name Display name for this server profile.
   * @param baseUrl Server API address; normalized before pairing.
   * @param pairingCode One-time code generated by the server.
   * @param deviceName Name registered for this app installation.
   * @throws {Error} If inputs are invalid, pairing fails, or persistence fails.
   */
  async function addProfile(
    name: string,
    baseUrl: string,
    pairingCode: string,
    deviceName: string,
  ): Promise<void> {
    if (isLoading) {
      throw new Error("Saved server profiles are still loading. Try again shortly.");
    }
    if (profilesLoadFailed) {
      throw new Error("Saved server profiles could not be loaded. Restart the app and try again.");
    }

    const normalizedUrl = normalizeServerUrl(baseUrl);
    const profileName = name.trim();
    const mobileDeviceName = deviceName.trim();
    const code = pairingCode.trim();

    if (!profileName) throw new Error("Enter a name for this server.");
    if (!mobileDeviceName) throw new Error("Enter a name for this device.");
    if (!code) throw new Error("Enter the pairing code shown by the server.");

    const response = await exchangePairingCode(
      new OpenRgbClient({ baseUrl: normalizedUrl }),
      code,
      mobileDeviceName,
    );
    const profile: ServerProfile = {
      id: newProfileId(),
      name: profileName,
      baseUrl: normalizedUrl,
      deviceId: response.device.id,
    };
    const updatedProfiles = [...profiles, profile];

    await saveAccessToken(profile.id, response.access_token);
    try {
      await saveServerProfiles(updatedProfiles);
    } catch (error) {
      // Do not leave an orphaned secret if persisting its profile fails.
      await deleteAccessToken(profile.id);
      throw error;
    }

    setProfiles(updatedProfiles);
    setStatuses((current) => ({ ...current, [profile.id]: "online" }));
  }

  /**
   * Verifies a saved server and makes it the active authenticated session.
   * @param profile Previously paired server profile.
   * @throws {Error} If the server is unreachable or its token is unavailable.
   */
  async function connectProfile(profile: ServerProfile): Promise<void> {
    setStatuses((current) => ({ ...current, [profile.id]: "checking" }));
    try {
      const client = new OpenRgbClient({ baseUrl: profile.baseUrl });
      await checkServerHealth(client);
      const token = await getAccessToken(profile.id);
      if (!token)
        throw new Error(
          "This profile has no saved access token. Add it again.",
        );
      const authenticatedClient = new OpenRgbClient({
        baseUrl: profile.baseUrl,
        accessToken: token,
      });
      const serverVersion = await getServerVersion(authenticatedClient);
      assertClientCompatible(serverVersion);
      setStatuses((current) => ({ ...current, [profile.id]: "online" }));
      setActiveProfileId(profile.id);
      setActiveAccessToken(token);
      setActiveServerVersion(serverVersion);
    } catch (error) {
      setStatuses((current) => ({
        ...current,
        [profile.id]: error instanceof ClientCompatibilityError ? "online" : "offline",
      }));
      throw error;
    }
  }

  /**
   * Removes profile metadata and its bearer token, disconnecting if active.
   * @param profile Profile to remove.
   * @throws Propagates storage failures so the caller can show an error.
   */
  async function removeProfile(profile: ServerProfile): Promise<void> {
    const updatedProfiles = profiles.filter(({ id }) => id !== profile.id);
    await saveServerProfiles(updatedProfiles);
    await deleteAccessToken(profile.id);
    setProfiles(updatedProfiles);
    setStatuses((current) => {
      const next = { ...current };
      delete next[profile.id];
      return next;
    });
    if (activeProfileId === profile.id) {
      setActiveProfileId(null);
      setActiveAccessToken(null);
      setActiveServerVersion(null);
    }
  }

  /** Clears active connection state without deleting the saved profile. */
  function disconnect() {
    setActiveProfileId(null);
    setActiveAccessToken(null);
    setActiveServerVersion(null);
  }

  return {
    profiles,
    statuses,
    isLoading,
    activeProfile: profiles.find(({ id }) => id === activeProfileId) ?? null,
    activeAccessToken,
    activeServerVersion,
    addProfile,
    connectProfile,
    removeProfile,
    disconnect,
  };
}
