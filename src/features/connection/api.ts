import { OpenRgbClient } from "@/services/openrgb/client";

/** Maximum time to wait for a pairing exchange before letting the user retry. */
const pairingRequestTimeoutMs = 10_000;

/** Health endpoint response used to check server reachability. */
export type ServerHealth = {
  status: "ok";
};

/** Version and capabilities advertised by an OpenRGB API service. */
export type ServerVersion = {
  apiVersion: number;
  minimumClientVersion: string;
  recommendedApiVersion: number;
  features: string[];
  message?: string;
};

/** Response returned after exchanging a pairing code. */
export type PairingExchange = {
  access_token: string;
  token_type: "Bearer";
  device: {
    id: string;
    name: string;
    created_at: string;
  };
};

/** Validated contents encoded in a pairing QR code. */
export type PairingQrPayload = {
  server_url: string;
  code: string;
  expires_at: string;
};

/**
 * Checks whether an OpenRGB API service is reachable.
 * @param client Client configured for the target server.
 * @returns The server's health response.
 * @throws {Error} When the server cannot be reached or returns an error.
 */
export function checkServerHealth(
  client: OpenRgbClient,
): Promise<ServerHealth> {
  return client.get<ServerHealth>("/health");
}

/**
 * Reads the authenticated version and capability document after pairing.
 * @param client Authenticated client for the target server.
 * @returns Server API version, client floor, recommendation, and capabilities.
 * @throws {Error} When the endpoint fails or returns an invalid document.
 */
export async function getServerVersion(
  client: OpenRgbClient,
): Promise<ServerVersion> {
  const value = await client.get<unknown>("/api/version");
  if (
    typeof value !== "object" || value === null ||
    !("apiVersion" in value) ||
    typeof value.apiVersion !== "number" ||
    !Number.isInteger(value.apiVersion) ||
    value.apiVersion < 1 ||
    !("minimumClientVersion" in value) || typeof value.minimumClientVersion !== "string" ||
    !("recommendedApiVersion" in value) ||
    typeof value.recommendedApiVersion !== "number" ||
    !Number.isInteger(value.recommendedApiVersion) ||
    value.recommendedApiVersion < 1 ||
    !("features" in value) || !Array.isArray(value.features) ||
    !value.features.every((feature) => typeof feature === "string") ||
    ("message" in value && typeof value.message !== "string")
  ) {
    throw new Error("The server returned an invalid version document.");
  }
  return value as ServerVersion;
}

/**
 * Exchanges a one-time pairing code for a device bearer token.
 * @param client Unauthenticated client for the server being paired.
 * @param code One-time code generated by the server's control panel.
 * @param deviceName Name recorded for this paired app installation.
 * @returns Token and device metadata returned by the pairing endpoint.
 * @throws {Error} When the code is rejected or the request fails.
 */
export function exchangePairingCode(
  client: OpenRgbClient,
  code: string,
  deviceName: string,
): Promise<PairingExchange> {
  const controller = new AbortController();
  const timeout = setTimeout(
    () => controller.abort(),
    pairingRequestTimeoutMs,
  );

  return client
    .post<PairingExchange>(
      "/api/pairing/exchange",
      { code, device_name: deviceName },
      controller.signal,
    )
    .catch((error: unknown) => {
      if (controller.signal.aborted) {
        throw new Error(
          "Pairing timed out after 10 seconds. Check the server address and network, then try again.",
        );
      }
      throw error;
    })
    .finally(() => clearTimeout(timeout));
}

/**
 * Parses and validates an OpenRGB pairing QR payload, including its expiry.
 * @param data Raw QR barcode contents.
 * @returns Validated server URL, pairing code, and expiry timestamp.
 * @throws {Error} If the payload is malformed, uses an unsupported URL scheme,
 *   or has expired.
 */
export function parsePairingQr(data: string): PairingQrPayload {
  let payload: unknown;
  try {
    payload = JSON.parse(data);
  } catch {
    throw new Error("This QR code is not an OpenRGB pairing code.");
  }

  if (typeof payload !== "object" || payload === null) {
    throw new Error("This QR code is not an OpenRGB pairing code.");
  }

  const qr = payload as Partial<PairingQrPayload>;
  if (
    typeof qr.server_url !== "string" ||
    typeof qr.code !== "string" ||
    typeof qr.expires_at !== "string"
  ) {
    throw new Error("This QR code is missing pairing details.");
  }

  let serverUrl: URL;
  try {
    serverUrl = new URL(qr.server_url);
  } catch {
    throw new Error("The QR code contains an invalid server address.");
  }
  if (serverUrl.protocol !== "http:" && serverUrl.protocol !== "https:") {
    throw new Error("The QR code must use an HTTP or HTTPS server address.");
  }
  if (
    !Number.isFinite(Date.parse(qr.expires_at)) ||
    Date.parse(qr.expires_at) <= Date.now()
  ) {
    throw new Error(
      "This pairing QR code has expired. Generate a new one on the server.",
    );
  }

  return {
    server_url: serverUrl.toString().replace(/\/$/, ""),
    code: qr.code,
    expires_at: qr.expires_at,
  };
}
